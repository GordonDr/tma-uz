// Офлайн-режим чек-листа (G-03).
//
// Зачем. Чек-листом пользуются ровно в один момент: человек стоит в пустой
// квартире в сдающемся доме и идёт по пунктам. Интернета там обычно нет —
// ни проводного, ни толкового мобильного: бетон, минус первый этаж, дом ещё
// не подключён. До этого отметки хранились на устройстве, а сама страница
// грузилась из сети — то есть в момент, ради которого продукт существует,
// он не открывался вообще.
//
// Стратегия намеренно разная для двух видов запросов:
//
//   · Оболочка и данные (html, js, иконки) — сначала кэш, потом сеть.
//     Открывается мгновенно и работает без сети. Свежесть догоняется фоном:
//     ответ из сети кладётся в кэш и применится при следующем открытии.
//     Для чек-листа это правильный размен: устареть на один заход не страшно,
//     не открыться — страшно.
//
//   · Обращения к функции (заказы, фото) — только сеть, без кэша.
//     Кэшировать ответы про заказ нельзя: показать вчерашний статус заказа
//     хуже, чем честно сказать «нет сети».
//
// Версия кэша подставляется скриптом деплоя. Без этого старая оболочка
// пережила бы выкатку и человек чинил бы её очисткой браузера — то есть никогда.

const VERSION = "20260826-213722";
const CACHE = "kq-" + VERSION;

// Точный список, а не «всё, что попросят»: так на установке видно, если файл
// переименовали и забыли, — установка упадёт, и это заметно сразу.
const SHELL = [
  "./",
  "./index.html",
  "./checklist-data.js",
  "./config.js",
  "./favicon.png",
];

self.addEventListener("install", (e) => {
  e.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(SHELL))
      // Ждать закрытия всех вкладок незачем: у мини-аппа вкладка одна,
      // и она же — та, которой нужна новая версия.
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;

  const url = new URL(req.url);
  // Чужой домен — не наше дело: функции, Telegram, шрифты. Пусть идут в сеть
  // как шли. Молча закэшировать чужой ответ — верный способ однажды показать
  // человеку чужие устаревшие данные и не понять, откуда они взялись.
  if (url.origin !== self.location.origin) return;

  e.respondWith(
    caches.match(req).then((hit) => {
      const fromNet = fetch(req)
        .then((res) => {
          // Кладём только удачные ответы своего происхождения. Иначе 404
          // с сервера Pages въезжает в кэш и живёт там до следующей выкатки.
          if (res && res.ok && res.type === "basic") {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => hit);   // сети нет — отдаём то, что есть

      // Кэш есть — отдаём немедленно, сеть догоняет в фоне.
      return hit || fromNet;
    })
  );
});
